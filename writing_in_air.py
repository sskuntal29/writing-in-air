class GestureTranslator(nn.Module):
    def __init__(self, opts):
        super().__init__()
        self.opts = opts

        alpha_map = {'english': ALPHABET, 'korean': HANGUL}
        alpha = alpha_map.get(opts.data_type, ALPHA_HAN)
        # FIX: CTC only needs +1 for blank token (index 0), chars use indices 1-27
        self.num_class = len(alpha) + 1  # Was: len(alpha) + (2 if opts.loss_type == 'ctc' else 1)

        builders = {'r3d': r3d, 'mc3': mc3, 'rmc3': rmc3, 'twoplusone': r2plus1d, 'r2d': r2d}
        self.encoder_module = builders[opts.model_type]()

        if opts.pretrained:
            # Use weights=None / weights=... API (no deprecation warning)
            pt_map = {
                'r3d':      torchvision.models.video.R3D_18_Weights.DEFAULT,
                'mc3':      torchvision.models.video.MC3_18_Weights.DEFAULT,
                'twoplusone': torchvision.models.video.R2Plus1D_18_Weights.DEFAULT,
            }
            if opts.model_type in pt_map:
                try:
                    model_ft = getattr(torchvision.models.video,
                                       {'r3d':'r3d_18','mc3':'mc3_18','twoplusone':'r2plus1d_18'}[opts.model_type])(
                                       weights=pt_map[opts.model_type])
                except Exception:
                    model_ft = getattr(torchvision.models.video,
                                       {'r3d':'r3d_18','mc3':'mc3_18','twoplusone':'r2plus1d_18'}[opts.model_type])(
                                       pretrained=True)
                pre = model_ft.state_dict()
                pre.pop('fc.weight', None); pre.pop('fc.bias', None)
                enc = self.encoder_module.state_dict()
                enc.update(pre)
                self.encoder_module.load_state_dict(enc)

        self.recurrent_module = None
        rt = opts.recurrent_type.lower()
        if rt == 'lstm':
            self.recurrent_module = nn.LSTM(opts.input_size, opts.hidden_size,
                                            opts.num_layers, batch_first=True, bidirectional=True)
        elif rt == 'gru':
            self.recurrent_module = nn.GRU(opts.input_size, opts.hidden_size,
                                           opts.num_layers, batch_first=True, bidirectional=True)
        elif rt == 'transformers':
            enc_layer = nn.TransformerEncoderLayer(d_model=opts.d_model, nhead=opts.nhead, batch_first=True)
            self.recurrent_module = nn.TransformerEncoder(enc_layer, opts.num_encoder_layer)

        if self.recurrent_module and rt != 'transformers':
            self.fc1 = nn.Linear(2 * opts.hidden_size, opts.hidden_size_fc)
        elif self.recurrent_module and rt == 'transformers':
            self.fc1 = nn.Linear(opts.d_model, opts.hidden_size_fc)
        else:
            self.fc1 = None

        in_fc2 = opts.hidden_size_fc if self.fc1 else opts.input_size
        self.fc2 = nn.Linear(in_fc2, self.num_class)

    def forward(self, seq_img, seq_lens):
        emb = self.encoder_module(seq_img.permute(0,2,1,3,4))
        rt = self.opts.recurrent_type.lower()
        if self.recurrent_module and rt != 'transformers':
            packed, _ = self.recurrent_module(
                pack_padded_sequence(emb, seq_lens.cpu(), batch_first=True, enforce_sorted=False))
            emb, _ = pad_packed_sequence(packed, batch_first=True)
            return self.fc2(F.relu(self.fc1(emb)))
        elif self.recurrent_module:
            return self.fc2(F.relu(self.fc1(self.recurrent_module(emb))))
        return self.fc2(emb)

