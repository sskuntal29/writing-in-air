class BasicBlock(nn.Module):
    expansion = 1
    def __init__(self, inplanes, planes, conv_builder, stride=1, downsample=None):
        midplanes = (inplanes * planes * 27) // (inplanes * 9 + 3 * planes)
        super().__init__()
        self.conv1 = nn.Sequential(
            conv_builder(inplanes, planes, midplanes, stride),
            nn.BatchNorm3d(planes, track_running_stats=TRACK_RUNNING), nn.ReLU(inplace=True))
        self.conv2 = nn.Sequential(
            conv_builder(planes, planes, midplanes),
            nn.BatchNorm3d(planes, track_running_stats=TRACK_RUNNING))
        self.relu = nn.ReLU(inplace=True)
        self.downsample = downsample

    def forward(self, x):
        residual = x
        out = self.conv2(self.conv1(x))
        if self.downsample: residual = self.downsample(x)
        return self.relu(out + residual)


