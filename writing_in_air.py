class ColorJitter:
    def __init__(self, brightness=0, contrast=0, saturation=0, hue=0):
        self.brightness = brightness
        self.contrast   = contrast
        self.saturation = saturation
        self.hue        = hue

    def get_params(self, b, c, s, h):
        def rf(x): return random.uniform(max(0, 1-x), 1+x) if x else None
        return rf(b), rf(c), rf(s), random.uniform(-h, h) if h else None

    def __call__(self, clip):
        b, c, s, h = self.get_params(self.brightness, self.contrast, self.saturation, self.hue)
        fns = []
        if b is not None: fns.append(lambda img, _b=b: TF.adjust_brightness(img, _b))
        if s is not None: fns.append(lambda img, _s=s: TF.adjust_saturation(img, _s))
        if h is not None: fns.append(lambda img, _h=h: TF.adjust_hue(img, _h))
        if c is not None: fns.append(lambda img, _c=c: TF.adjust_contrast(img, _c))
        random.shuffle(fns)
        out = []
        for img in clip:
            for fn in fns: img = fn(img)
            out.append(img)
        return out


class RandomRotation:
    def __init__(self, degrees):
        if isinstance(degrees, numbers.Number):
            self.degrees = (-abs(degrees), abs(degrees))
        else:
            self.degrees = degrees

    def __call__(self, clip):
        angle = random.uniform(*self.degrees)
        if isinstance(clip[0], np.ndarray):
            return [skimage_transform.rotate(f, angle) for f in clip]
        elif isinstance(clip[0], Image.Image):
            return [f.rotate(angle) for f in clip]
        raise TypeError(type(clip[0]))

