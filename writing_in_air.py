def convert_img(img):
    if len(img.shape) == 3: return img.transpose(2, 0, 1)
    if len(img.shape) == 2: return np.expand_dims(img, 0)
    return img


def _is_tensor_clip(clip):
    return torch.is_tensor(clip) and clip.ndimension() == 4


def normalize_clip(clip, mean, std, inplace=False):
    if not inplace: clip = clip.clone()
    dtype = clip.dtype
    mean = torch.as_tensor(mean, dtype=dtype, device=clip.device)
    std  = torch.as_tensor(std,  dtype=dtype, device=clip.device)
    clip.sub_(mean[:, None, None, None]).div_(std[:, None, None, None])
    return clip


class ClipToTensor:
    def __init__(self, channel_nb=3, div_255=True, numpy=False):
        self.channel_nb = channel_nb
        self.div_255 = div_255
        self.numpy = numpy

    def __call__(self, clip):
        if isinstance(clip[0], np.ndarray):
            h, w, ch = clip[0].shape
        elif isinstance(clip[0], Image.Image):
            w, h = clip[0].size
        else:
            raise TypeError(type(clip[0]))
        np_clip = np.zeros([self.channel_nb, len(clip), int(h), int(w)])
        for i, img in enumerate(clip):
            if isinstance(img, Image.Image): img = np.array(img, copy=False)
            np_clip[:, i] = convert_img(img)
        if self.numpy:
            return np_clip / 255 if self.div_255 else np_clip
        t = torch.from_numpy(np_clip).float()
        return t.div(255) if self.div_255 else t


