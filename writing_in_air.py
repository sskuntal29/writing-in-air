def pad_collate(batch):
    xx, yy = zip(*batch)
    yy_pad = pad_sequence(yy, batch_first=True, padding_value=0)
    xx_pad = pad_sequence(xx, batch_first=True, padding_value=0)

    eng = opts.data_type == 'english'
    kor1 = opts.data_type == 'korean' and opts.num_res_layer == 1
    kor2 = opts.data_type == 'korean' and opts.num_res_layer == 2

    if eng or kor1:
        fn_map = {'r3d': calc_seq_len, 'twoplusone': calc_seq_len,
                  'rmc3': calc_seq_len_rmc3, 'mc3': calc_seq_len_mc3, 'r2d': calc_seq_len_2d_eng}
        fn = fn_map.get(opts.model_type, calc_seq_len)
    elif kor2:
        fn_map = {'r3d': seq_len_r3d_kor, 'twoplusone': calc_seq_len,
                  'rmc3': seq_len_rmc3_kor, 'mc3': seq_len_mc3_kor, 'r2d': calc_seq_len_2d_kor}
        fn = fn_map.get(opts.model_type, seq_len_r3d_kor)

    x_lens = torch.LongTensor([fn(len(x)) for x in xx])
    y_lens = torch.LongTensor([len(y) for y in yy])
    return xx_pad, yy_pad, x_lens, y_lens

class Trainer:
    def __init__(self, opts):
        self.opts = opts
        self.save_dir = os.path.join(opts.save_dir, opts.model_name)
        os.makedirs(self.save_dir, exist_ok=True)

        logging.basicConfig(
            filename=os.path.join(self.save_dir, 'log-train.log'),
            format='%(asctime)s %(message)s', datefmt='%m/%d/%Y %p %I:%M:%S',
            level=logging.INFO)
        self.logger = logging.getLogger('trainLogger')
        if not self.logger.handlers:
            self.logger.addHandler(logging.StreamHandler(sys.stdout))

        self.device = torch.device('cuda' if torch.cuda.is_available() else 'cpu')

        # Datasets
        data_train = AirTypingDataset(opts, opts.data_path_train)
        data_val   = AirTypingDataset(opts, opts.data_path_val)
        data_test  = AirTypingDataset(opts, opts.data_path_test)

        dl_kw = dict(batch_size=opts.batch_size, collate_fn=pad_collate,
                     num_workers=opts.num_workers, drop_last=True)
        self.data_loader_train = DataLoader(data_train, shuffle=True,  **dl_kw)
        self.data_loader_val   = DataLoader(data_val,   shuffle=False, **dl_kw)
        self.data_loader_test  = DataLoader(data_test,  shuffle=False, **dl_kw)

        self.model = GestureTranslator(opts).to(self.device)
        self.model_without_dp = self.model
        if torch.cuda.device_count() > 1:
            self.model = nn.DataParallel(self.model)
            self.model_without_dp = self.model.module
        self.logger.info(f'Device: {self.device}')

        params = list(self.model_without_dp.parameters())
        opt_map = {
            'adam':    torch.optim.Adam,
            'adamW':   torch.optim.AdamW,
            'sgd':     torch.optim.SGD,
            'rmsprop': torch.optim.RMSprop,
            'lamb':    Lamb,
        }
        self.optimizer = opt_map[opts.optimizer_type](params, lr=opts.learning_rate)

        iter_size = len(self.data_loader_train)
        step = opts.scheduler_step_size * iter_size
        if opts.scheduler_type == 'warmup':
            self.scheduler = WarmupMultiStepLR(
                self.optimizer, [step*(i+1) for i in range(opts.num_epochs)],
                gamma=opts.scheduler_gamma, warmup_iters=500)
        elif opts.scheduler_type == 'steplr':
            self.scheduler = torch.optim.lr_scheduler.StepLR(
                self.optimizer, step_size=step, gamma=opts.scheduler_gamma)
        else:
            self.scheduler = None

        if opts.load_dir:
            self.load_model()

        self.ctc_loss = nn.CTCLoss(reduction='mean', zero_infinity=True)
        self.epoch = self.step = self.start_step = 0
        self.start_time = time.time()
        self.num_total_steps = iter_size * opts.num_epochs
        self.best_val_cer = float('inf')
        self.save_opts()

    # ── Training loop ──────────────────────────────────────────────────────
    def train(self):
        for self.epoch in range(self.opts.num_epochs):
            print(f'Epoch {self.epoch}')
            self.model.train()
            self.run_one_epoch()
            is_best = self.validate(self.data_loader_val)
            if is_best or (self.opts.save_frequency > 0 and
                           (self.epoch+1) % self.opts.save_frequency == 0):
                self.save_model(is_best)

    def run_one_epoch(self):
        losses = []
        for bi, (xp, yp, xl, yl) in enumerate(self.data_loader_train):
            t0 = time.time()
            xp, yp = xp.to(self.device), yp.to(self.device)
            xl, yl = xl.to(self.device), yl.to(self.device)
            self.optimizer.zero_grad()
            out = self.model(xp, xl).permute(1,0,2).log_softmax(2)
            loss = self.ctc_loss(out, yp, xl, yl)
            losses.append(loss.item())
            loss.backward()
            self.optimizer.step()
            if self.scheduler: self.scheduler.step()
            if (bi+1) % self.opts.log_interval == 0:
                self.log_time(time.time()-t0, bi, loss.item())
                y_pred = torch.max(out, 2)[1]
                self.logger.info('\tGT  : ' + self.data_loader_train.dataset.converter.decode(yp[0,:yl[0]], yl[:1]))
                self.logger.info('\tPred: ' + self.data_loader_train.dataset.converter.decode(y_pred[:xl[0],0], xl[:1]))
            self.step += 1
        return losses

    def validate(self, data_loader, load=False):
        self.logger.info('--- Validation ---')
        if load: self.load_model()
        self.model.eval()
        losses, total_err, total_len = [], 0, 0
        with torch.no_grad():
            for bi, (xp, yp, xl, yl) in enumerate(data_loader):
                xp, yp = xp.to(self.device), yp.to(self.device)
                xl, yl = xl.to(self.device), yl.to(self.device)
                out = self.model(xp, xl).permute(1,0,2).log_softmax(2)
                losses.append(self.ctc_loss(out, yp, xl, yl).item())
                y_pred = torch.max(out, 2)[1]
                gt   = data_loader.dataset.converter.decode(yp[0,:yl[0]], yl[:1])
                pred = data_loader.dataset.converter.decode(y_pred[:xl[0],0], xl[:1])
                err, length = cer(gt, pred)
                total_err += min(err, length); total_len += length
                if (bi+1) % self.opts.log_interval == 0:
                    self.logger.info(f'\tGT  : {gt}'); self.logger.info(f'\tPred: {pred}')
        cur_cer = total_err / max(total_len, 1)
        self.logger.info(f'\tval_loss={sum(losses)/len(losses):.4f}  val_cer={cur_cer:.4f}')
        if cur_cer < self.best_val_cer:
            self.best_val_cer = cur_cer
            return True
        return False

    def log_time(self, duration, bi, loss):
        sps = self.opts.batch_size / max(duration, 1e-6)
        elapsed = time.time() - self.start_time
        left = ((self.num_total_steps - self.step) / max(self.step - self.start_step, 1)) * elapsed
        self.logger.info(
            f'epoch {self.epoch:3d} | batch [{bi*self.opts.batch_size:4d}/{len(self.data_loader_train.dataset)}]'
            f' | ex/s:{sps:5.1f} | loss:{loss:.5f} | elapsed:{sec_to_hm_str(elapsed)} | left:{sec_to_hm_str(left)}')

    def save_opts(self):
        with open(os.path.join(self.save_dir, 'opts.json'), 'w') as f:
            json.dump(self.opts.__dict__, f, indent=2)

    def save_model(self, is_best):
        tag = f'weights_{self.epoch}{"_best" if is_best else ""}'
        folder = os.path.join(self.save_dir, 'models', tag)
        os.makedirs(folder, exist_ok=True)
        torch.save(self.model_without_dp.state_dict(), os.path.join(folder, 'model.pth'))
        torch.save(self.optimizer.state_dict(),         os.path.join(folder, 'optimizer.pth'))
        if self.scheduler:
            torch.save(self.scheduler.state_dict(), os.path.join(folder, 'scheduler.pth'))
        print(f'Saved checkpoint → {folder}')

    def load_model(self):
        d = os.path.expanduser(self.opts.load_dir)
        assert os.path.isdir(d), f'Cannot find {d}'
        print(f'Loading model from {d}')
        self.model_without_dp.load_state_dict(torch.load(os.path.join(d, 'model.pth'), map_location=self.device))
        for name, cls in [('optimizer', self.optimizer), ('scheduler', self.scheduler)]:
            p = os.path.join(d, f'{name}.pth')
            if cls and os.path.isfile(p):
                cls.load_state_dict(torch.load(p, map_location=self.device))

