class AirTypingDataset(Dataset):
    def __init__(self, opts, data_path):
        self.data_path    = data_path
        self.data_type    = opts.data_type
        self.data_augment = opts.data_augment

        alpha_map = {'english': (ALPHABET, True), 'korean': (HANGUL, False)}
        alpha, ic = alpha_map.get(opts.data_type, (ALPHA_HAN, False))
        self.converter = StrLabelConverter(alpha, ic)

        self.video_list = []
        for group_dir in sorted(glob.glob(os.path.join(data_path, '*'))):
            if not os.path.isdir(group_dir): continue
            if not os.path.exists(os.path.join(group_dir, 'gt.txt')): continue
            for item in os.listdir(group_dir):
                vdir = os.path.join(group_dir, item)
                if os.path.isdir(vdir) and item.isdigit():
                    if any(f.endswith('.png') for f in os.listdir(vdir)):
                        self.video_list.append(vdir)

        self.img_size = opts.img_size
        self.resize = transforms.Resize(112)

        self.video_transform = VideoCompose([
            ClipToTensor(channel_nb=3),
            VideoNormalize(mean=[0.485,0.456,0.406], std=[0.229,0.224,0.225])
        ])
        self.video_transform_aug = VideoCompose([
            ColorJitter(0.5,0.5,0.5,0.5),
            RandomRotation(5),
            ClipToTensor(channel_nb=3),
            VideoNormalize(mean=[0.485,0.456,0.406], std=[0.229,0.224,0.225])
        ])

        self.labels = []
        for vname in self.video_list:
            idx = int(os.path.basename(vname))
            gt_path = os.path.join(os.path.dirname(vname), 'gt.txt')
            if self.data_type == 'english':
                with open(gt_path, 'r') as f:
                    self.labels.append(f.readlines()[idx].strip())
            elif self.data_type == 'korean':
                with open(gt_path, 'rb') as f:
                    self.labels.append(f.readlines()[idx][:-2].decode('cp949'))

        print(f'Dataset loaded from {data_path}: {len(self.video_list)} samples')

    def __len__(self):  return len(self.video_list)

    def __getitem__(self, i):
        return self.read_images(i).permute(1,0,2,3), self.read_labels(i)

    def read_images(self, i):
        vdir = self.video_list[i]
        if os.path.isfile(vdir): vdir = os.path.dirname(vdir)
        frames = sorted(f for f in os.listdir(vdir) if f.endswith('.png'))
        imgs = []
        for fn in frames:
            img = Image.open(os.path.join(vdir, fn))
            if self.img_size == 112: img = self.resize(img)
            imgs.append(img)
        return self.video_transform_aug(imgs) if self.data_augment else self.video_transform(imgs)

    def read_labels(self, i):
        raw = hgtk.text.decompose(self.labels[i]) if self.data_type == 'korean' else self.labels[i]
        enc, _ = self.converter.encode(raw)
        return enc

