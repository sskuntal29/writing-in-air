class WarmupMultiStepLR(torch.optim.lr_scheduler._LRScheduler):
    def __init__(self, optimizer, milestones, gamma=0.1,
                 warmup_factor=1/3, warmup_iters=500,
                 warmup_method='linear', last_epoch=-1):
        assert list(milestones) == sorted(milestones), 'Milestones must be sorted'
        assert warmup_method in ('constant', 'linear')
        self.milestones = milestones
        self.gamma = gamma
        self.warmup_factor = warmup_factor
        self.warmup_iters = warmup_iters
        self.warmup_method = warmup_method
        super().__init__(optimizer, last_epoch)

    def get_lr(self):
        wf = 1
        if self.last_epoch < self.warmup_iters:
            if self.warmup_method == 'constant':
                wf = self.warmup_factor
            else:
                alpha = self.last_epoch / self.warmup_iters
                wf = self.warmup_factor * (1 - alpha) + alpha
        return [lr * wf * self.gamma ** bisect_right(self.milestones, self.last_epoch)
                for lr in self.base_lrs]


class Lamb(Optimizer):
    """LAMB optimizer — large-batch training."""
    def __init__(self, params, lr=1e-3, betas=(0.9, 0.999), eps=1e-6,
                 weight_decay=0, adam=False):
        defaults = dict(lr=lr, betas=betas, eps=eps, weight_decay=weight_decay)
        self.adam = adam
        super().__init__(params, defaults)

    def step(self, closure=None):
        loss = closure() if closure else None
        for group in self.param_groups:
            for p in group['params']:
                if p.grad is None: continue
                grad = p.grad.data
                state = self.state[p]
                if not state:
                    state['step'] = 0
                    state['exp_avg']    = torch.zeros_like(p.data)
                    state['exp_avg_sq'] = torch.zeros_like(p.data)
                ea, eas = state['exp_avg'], state['exp_avg_sq']
                b1, b2  = group['betas']
                state['step'] += 1
                ea.mul_(b1).add_(grad, alpha=1 - b1)
                eas.mul_(b2).addcmul_(grad, grad, value=1 - b2)
                adam_step = ea / eas.sqrt().add(group['eps'])
                if group['weight_decay']:
                    adam_step.add_(p.data, alpha=group['weight_decay'])
                wn = p.data.pow(2).sum().sqrt().clamp(0, 10)
                an = adam_step.pow(2).sum().sqrt()
                tr = 1 if (wn == 0 or an == 0 or self.adam) else wn / an
                p.data.add_(adam_step, alpha=-group['lr'] * tr)
        return loss

