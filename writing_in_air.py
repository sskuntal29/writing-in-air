class StrLabelConverter:
    """Encode/decode strings to/from integer label tensors for CTC."""

    def __init__(self, alphabet, ignore_case=True):
        self._ignore_case = ignore_case
        if ignore_case:
            alphabet = alphabet.lower()
        self.alphabet = alphabet + '-'
        self.dict = {c: i + 1 for i, c in enumerate(self.alphabet)}

    def encode(self, text):
        if isinstance(text, str):
            lst, prev = [], ''
            for ch in text:
                if ch == prev:
                    lst.append(self.dict['-'])
                lst.append(self.dict[ch.lower() if self._ignore_case else ch])
                prev = ch
            return torch.IntTensor(lst), torch.IntTensor([len(lst)])
        elif isinstance(text, collections.abc.Iterable):
            lengths = [len(s) for s in text]
            joined, _ = self.encode(''.join(text))
            return joined, torch.IntTensor(lengths)

    def decode(self, t, length, raw=False):
        if length.numel() == 1:
            length = length[0]
            assert t.numel() == length
            if raw:
                return ''.join(self.alphabet[i - 1] for i in t)
            chars = []
            for i in range(int(length)):
                if t[i] != 0 and not (i > 0 and t[i - 1] == t[i]):
                    chars.append(self.alphabet[t[i] - 1])
            return ''.join(chars)
        texts, idx = [], 0
        for l in length:
            texts.append(self.decode(t[idx: idx + l], torch.IntTensor([l]), raw))
            idx += l
        return texts


def cer(ref, hyp):
    ref = re.sub(r'^<START>|<EOS>$', '', ref)
    hyp = re.sub(r'^<START>|<EOS>$', '', hyp)
    return editdistance.eval(ref, hyp), len(ref)

