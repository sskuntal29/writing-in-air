def inference_single_video(model, video_path, opts):
    """Run inference on one folder of PNG frames."""
    device = torch.device('cuda' if torch.cuda.is_available() else 'cpu')
    model.eval()
    vt = VideoCompose([
        ClipToTensor(channel_nb=3),
        VideoNormalize(mean=[0.485,0.456,0.406], std=[0.229,0.224,0.225])
    ])
    resize = transforms.Resize(112)
    frames = sorted(f for f in os.listdir(video_path) if f.endswith('.png'))
    imgs = []
    for fn in frames:
        img = Image.open(os.path.join(video_path, fn))
        if opts.img_size == 112: img = resize(img)
        imgs.append(img)
    vid = vt(imgs).permute(1,0,2,3).unsqueeze(0).to(device)
    fn_map = {'r3d': calc_seq_len, 'twoplusone': calc_seq_len,
              'mc3': calc_seq_len_mc3, 'rmc3': calc_seq_len_rmc3,
              'r2d': calc_seq_len_2d_eng}
    seq_len = fn_map.get(opts.model_type, calc_seq_len)(len(frames))
    xl = torch.LongTensor([seq_len]).to(device)
    with torch.no_grad():
        out = model(vid, xl).permute(1,0,2).log_softmax(2)
        y_pred = torch.max(out, 2)[1]
    return StrLabelConverter(ALPHABET).decode(y_pred[:xl[0], 0], xl[:1])

